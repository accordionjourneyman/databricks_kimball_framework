def _load_env_file(env_file: str | None) -> None:
    if env_file is None:
        env_file = str(REPO_ROOT / ".env")
    if not os.path.exists(env_file):
        return
    try:
        from dotenv import load_dotenv

        load_dotenv(env_file, override=True)
        print(f"[query-history] loaded environment from {env_file}", file=sys.stderr)
    except ImportError:
        pass


def run(
    *,
    days: int = 7,
    warehouse: str | None = None,
    json_output: bool = False,
    verbose: bool = False,
    env_file: str | None = None,
) -> int:
    """Run query-history analysis. Returns a process exit code."""
    _load_env_file(env_file)
    host = os.environ.get("DATABRICKS_HOST")
    token = os.environ.get("DATABRICKS_TOKEN")
    if not host or not token:
        print(
            "error: DATABRICKS_HOST and DATABRICKS_TOKEN must be set", file=sys.stderr
        )
        return 1
    try:
        from databricks.sdk import WorkspaceClient

        ws = WorkspaceClient(host=host, token=token)
    except ImportError:
        print(
            "error: databricks-sdk is not installed. Run: pip install '.[remote]'",
            file=sys.stderr,
        )
        return 1
    except Exception as exc:  # noqa: BLE001 - connection/credential failures
        print(f"error: cannot connect to Databricks: {exc}", file=sys.stderr)
        return 1

    try:
        rows = _fetch_history(ws, days=days, warehouse_id=warehouse, verbose=verbose)
    except Exception as exc:  # noqa: BLE001 - access-denied / retention / warehouse errors
        print(f"error: query history failed: {exc}", file=sys.stderr)
        print(
            "If access was denied, verify your token has the "
            "'databricks_query_history' permission, or reduce --days if retention "
            "has expired.",
            file=sys.stderr,
        )
        return 1

    if not rows:
        print("No queries found in the selected window.")
        return 0

    report = _analyze(rows, days=days)
    if json_output:
        print(json.dumps(report, indent=2, default=str))
    else:
        _print_report(report)
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "--days", type=int, default=7, help="Days of history (default: 7)"
    )
    parser.add_argument(
        "--warehouse", default=None, help="Warehouse ID (default: first running)"
    )
    parser.add_argument("--json", action="store_true", help="JSON output")
    parser.add_argument(
        "--verbose", action="store_true", help="Show the executed SQL (stderr)"
    )
    parser.add_argument("--env-file", default=None, help="Path to .env file")
    args = parser.parse_args()
    return run(
        days=args.days,
        warehouse=args.warehouse,
        json_output=args.json,
        verbose=args.verbose,
        env_file=args.env_file,
    )


if __name__ == "__main__":
    sys.exit(main())
